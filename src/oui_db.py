# Normalize keys without spaces at import time
_CLEAN_OUI_TABLE: dict[str, Tuple[str, str]] = {
    k.replace(" ", "").replace(":", "").replace("-", "").upper(): v
    for k, v in OUI_TABLE.items()
}


def is_randomized_mac(mac: str) -> bool:
    """Return True if MAC has the Locally Administered bit set (and is not a known VM OUI)."""
    clean = mac.replace(":", "").replace("-", "").replace(".", "").upper()
    if len(clean) < 6:
        return False
    if clean[:6] in VIRTUAL_OUIS:
        return False
    try:
        first_byte = int(clean[:2], 16)
    except ValueError:
        return False
    # Bit 1 (0x02) = Locally Administered, Bit 0 (0x01) = Multicast (should be 0 for unicast)
    return bool(first_byte & 0x02) and not bool(first_byte & 0x01)


def lookup_oui(mac: str) -> Tuple[str, str]:
    """Look up (vendor_name, media_hint) for a MAC address."""
    clean = mac.replace(":", "").replace("-", "").replace(".", "").upper()
    if len(clean) < 6:
        return ("Desconhecido", "unknown")
    prefix = clean[:6]
    if prefix in _CLEAN_OUI_TABLE:
        return _CLEAN_OUI_TABLE[prefix]
    if is_randomized_mac(mac):
        return ("MAC Aleatório (Privacidade)", "wifi")
    return ("Desconhecido", "unknown")
